#!/usr/bin/env node
// build-examples.mjs — turn delivered lesson projects into the public reference library in examples/.
//
//   node dev/build-examples.mjs <project-dir>…
//
// Per project it copies the authoring inputs and the built frames (text only), extracts one preview JPG
// per frame from the final MP4, and rewrites references to real account screenshots (assets/screens/)
// to a labeled placeholder: those screenshots stay private and are never copied. Frames that show one
// get no preview. Finally it writes examples/CATALOG.md, an index of every frame by shot type.

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(SKILL, "examples");
const projects = process.argv.slice(2);
if (!projects.length) {
  console.error("usage: build-examples.mjs <project-dir>…");
  process.exit(1);
}

const FILES = [
  "video.config.json", "script.src.txt", "STORYBOARD.md", "SCRIPT-REVIEW.md", "frame.md",
  "capture/extracted/visible-text.txt", "renders/qa-report.md", "renders/chapters.txt",
];
const PLACEHOLDER = "assets/screens/private-screenshot-placeholder.svg";
const placeholderSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">
  <rect width="1920" height="1080" fill="#141B3A"/>
  <rect x="24" y="24" width="1872" height="1032" fill="none" stroke="#8E93B5" stroke-width="4" stroke-dasharray="24 16"/>
  <text x="960" y="520" fill="#F4F1E8" font-family="sans-serif" font-size="64" text-anchor="middle">MINH HỌA</text>
  <text x="960" y="600" fill="#8E93B5" font-family="sans-serif" font-size="32" text-anchor="middle">A private account screenshot was here; it is not published.</text>
</svg>
`;

function frameBlocks(storyboard) {
  return storyboard.split(/(?=^## Frame \d+ )/m).filter((b) => /^## Frame \d+ /.test(b)).map((b) => {
    const get = (k) => b.match(new RegExp(`^- ${k}: (.+)$`, "m"))?.[1]?.trim();
    return {
      n: Number(b.match(/^## Frame (\d+) /)[1]),
      title: b.match(/^## Frame \d+ — (.+)$/m)?.[1]?.trim() ?? "",
      src: get("src"), chapter: get("chapter"), blueprint: get("blueprint") ?? "", shots: get("shots") ?? "",
      layout: get("layout"), duration: parseFloat(get("duration")),
    };
  });
}

const catalog = [];
for (const project of projects) {
  const name = basename(resolve(project));
  const dst = join(OUT, name);
  rmSync(dst, { recursive: true, force: true });
  mkdirSync(join(dst, "compositions/frames"), { recursive: true });
  mkdirSync(join(dst, "previews"), { recursive: true });
  for (const f of FILES) if (existsSync(join(project, f))) cpSync(join(project, f), join(dst, f));
  if (existsSync(join(project, "capture/terminal"))) cpSync(join(project, "capture/terminal"), join(dst, "capture/terminal"), { recursive: true });

  const frames = frameBlocks(readFileSync(join(project, "STORYBOARD.md"), "utf8"));
  const video = join(project, `renders/${name}.mp4`);
  let t = 0, privateFrames = 0;
  for (const fr of frames) {
    const file = basename(fr.src);
    let html = readFileSync(join(project, fr.src), "utf8");
    const hasScreen = /assets\/screens\/[^"')\s]+\.(png|jpe?g|webp)/.test(html);
    if (hasScreen) {
      html = html.replace(/assets\/screens\/[^"')\s]+\.(png|jpe?g|webp)/g, PLACEHOLDER);
      privateFrames++;
    }
    writeFileSync(join(dst, "compositions/frames", file), html);
    let preview = null;
    if (!hasScreen && existsSync(video)) {
      preview = `previews/${String(fr.n).padStart(2, "0")}.jpg`;
      const at = (t + 0.75 * fr.duration).toFixed(2);
      const r = spawnSync("ffmpeg", ["-v", "error", "-y", "-ss", at, "-i", video, "-frames:v", "1", "-vf", "scale=960:-1", "-q:v", "5", join(dst, preview)]);
      if (r.status !== 0) throw new Error(`preview ${name} frame ${fr.n} failed: ${r.stderr}`);
    }
    catalog.push({ video: name, ...fr, file, preview, hasScreen });
    t += fr.duration;
  }
  if (privateFrames) {
    mkdirSync(join(dst, "assets/screens"), { recursive: true });
    writeFileSync(join(dst, PLACEHOLDER), placeholderSvg);
  }
  console.log(`${name}: ${frames.length} frames, ${frames.length - privateFrames} previews, ${privateFrames} private screenshot frame(s) masked`);
}

// ── CATALOG.md ───────────────────────────────────────────────────────────────
const md = ["# Frame catalog", "",
  "Every frame of the example videos, generated by `dev/build-examples.mjs`. Use it to find a worked example of a shot type",
  "(for instance a `hub` or a `split`) before building a similar frame. The previews are taken at 75 % of each frame from the",
  "final video; frames that showed a private account screenshot have no preview.", ""];
const byType = new Map();
for (const f of catalog) for (const s of f.shots.split(",").map((x) => x.trim().split("@")[0]).filter(Boolean)) {
  if (!byType.has(s)) byType.set(s, []);
  if (!byType.get(s).includes(f)) byType.get(s).push(f);
}
md.push("## By shot type", "");
for (const [type, list] of [...byType].sort((a, b) => a[0].localeCompare(b[0]))) {
  md.push(`- **${type}** (${list.length}): ${list.map((f) => `[${f.video.split("-")[0]} ${f.n}](${f.video}/compositions/frames/${f.file})`).join(", ")}`);
}
for (const v of [...new Set(catalog.map((f) => f.video))]) {
  md.push("", `## ${v}`, "", "| # | frame | chapter | shots | blueprint | preview |", "|---|---|---|---|---|---|");
  for (const f of catalog.filter((x) => x.video === v)) {
    const prev = f.preview ? `![${f.n}](${v}/${f.preview})` : f.hasScreen ? "_(private screenshot)_" : "–";
    const bp = f.blueprint.replace(/\|/g, "/");
    md.push(`| ${f.n} | [${f.title.replace(/\|/g, "/")}](${v}/compositions/frames/${f.file}) | ${f.chapter} | \`${f.shots}\` | ${bp} | ${prev} |`);
  }
}
writeFileSync(join(OUT, "CATALOG.md"), md.join("\n") + "\n");
console.log(`examples/CATALOG.md: ${catalog.length} frames, ${byType.size} shot types`);
